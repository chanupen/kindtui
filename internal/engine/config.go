package engine

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// ConfigSummary is the part of a kind config the TUI shows before create.
type ConfigSummary struct {
	Name          string
	Path          string
	ControlPlanes int
	Workers       int
	NodesSet      bool
}

// Topology renders the summary the same way a live cluster does.
func (c ConfigSummary) Topology() string {
	cp := c.ControlPlanes
	if !c.NodesSet {
		cp = 1
	}
	parts := []string{plural(cp, "control-plane")}
	if c.Workers > 0 {
		parts = append(parts, plural(c.Workers, "worker"))
	}
	return strings.Join(parts, " · ")
}

var configNames = []string{
	"kind-cluster-config.yaml",
	"kind-config.yaml",
	"kind.yaml",
	"kind.yml",
}

// FindConfig looks for a kind config.
// KIND_CONFIG wins. Otherwise it walks up from start, or from the working
// directory when start is empty.
func FindConfig(start string) (string, error) {
	if p := strings.TrimSpace(os.Getenv("KIND_CONFIG")); p != "" {
		if isFile(p) {
			return p, nil
		}
		return "", fmt.Errorf("KIND_CONFIG=%s is not a file", p)
	}
	dir := start
	if dir == "" {
		var err error
		dir, err = os.Getwd()
		if err != nil {
			return "", err
		}
	}
	dir = filepath.Clean(dir)
	for i := 0; i < 8; i++ {
		for _, name := range configNames {
			p := filepath.Join(dir, name)
			if isFile(p) {
				return p, nil
			}
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	return "", os.ErrNotExist
}

func isFile(path string) bool {
	fi, err := os.Stat(path)
	return err == nil && !fi.IsDir()
}

type configFile struct {
	Name  string `yaml:"name"`
	Nodes *[]struct {
		Role string `yaml:"role"`
	} `yaml:"nodes"`
}

// ParseConfig reads a kind Cluster manifest.
// A missing nodes list means kind's default of one control plane.
// An empty nodes list is reported as zero nodes.
func ParseConfig(path string) (ConfigSummary, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return ConfigSummary{}, err
	}
	var raw configFile
	if err := yaml.Unmarshal(data, &raw); err != nil {
		return ConfigSummary{}, fmt.Errorf("parse %s: %w", path, err)
	}
	sum := ConfigSummary{Name: raw.Name, Path: path}
	if raw.Nodes == nil {
		sum.ControlPlanes = 1
		return sum, nil
	}
	sum.NodesSet = true
	for _, n := range *raw.Nodes {
		role := n.Role
		if role == "" {
			role = "control-plane"
		}
		switch role {
		case "control-plane":
			sum.ControlPlanes++
		case "worker":
			sum.Workers++
		default:
			sum.Workers++
		}
	}
	return sum, nil
}

// RenderConfig builds a kind manifest with one control plane and workers workers.
func RenderConfig(name string, workers int) string {
	if workers < 0 {
		workers = 0
	}
	var b strings.Builder
	b.WriteString("# generated by kindtui\n")
	b.WriteString("kind: Cluster\napiVersion: kind.x-k8s.io/v1alpha4\n")
	fmt.Fprintf(&b, "name: %s\nnodes:\n- role: control-plane\n", name)
	for i := 0; i < workers; i++ {
		b.WriteString("- role: worker\n")
	}
	return b.String()
}

// CreatePreview describes the kind invocation without writing a temp file.
func CreatePreview(spec CreateSpec) string {
	args := []string{"kind", "create", "cluster", "--name", spec.Name}
	if spec.ConfigPath != "" {
		args = append(args, "--config", spec.ConfigPath)
	} else {
		args = append(args, "--config", "<generated>")
	}
	if spec.Image != "" {
		args = append(args, "--image", spec.Image)
	}
	if spec.Wait > 0 {
		args = append(args, "--wait", spec.Wait.String())
	}
	return strings.Join(args, " ")
}
